/* 启动 ADC1 双通道 DMA 循环采集，开机调一次即可 */
void ADC_Start(void)
{
    HAL_ADC_Start_DMA(&hadc1, (uint32_t *)adc_dma_buf, 2);

    /* 循环模式下 DMA 自己搬数据，不需要 CPU 参与；HAL 启动时会打开
     * TC/HT/TE 中断，约每 11us 进一次（约 18 万次/秒），这里关掉。 */
    __HAL_DMA_DISABLE_IT(&hdma_adc1, DMA_IT_TC | DMA_IT_HT | DMA_IT_TE);
}

